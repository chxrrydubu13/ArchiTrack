<script>







document.addEventListener('DOMContentLoaded', function () {















    const body = document.body;







    const sidebar = document.getElementById('adminSidebar');







    const sidebarToggle = document.getElementById('sidebarToggle');







    const sidebarBackdrop = document.getElementById('sidebarBackdrop');







    const mobileSidebarLauncher = document.getElementById('mobileSidebarLauncher');







    const topbarMenuButton = document.getElementById('topbarMenuButton');















    const desktopMedia =







        window.matchMedia('(min-width: 701px)');























    function setDesktopCollapsed(collapsed) {















        if (!desktopMedia.matches) {







            return;







        }















        body.classList.toggle(







            'sidebar-collapsed',







            collapsed







        );















        sidebarToggle?.setAttribute(







            'aria-expanded',







            collapsed ? 'false' : 'true'







        );















        sidebarToggle?.setAttribute(







            'aria-label',







            collapsed







                ? 'Maximize sidebar'







                : 'Minimize sidebar'







        );















        localStorage.setItem(







            'architrackAdminSidebarCollapsed',







            collapsed ? '1' : '0'







        );















    }























    function openMobileSidebar() {















        if (desktopMedia.matches) {







            return;







        }















        body.classList.add(







            'mobile-sidebar-open'







        );















        mobileSidebarLauncher?.setAttribute(







            'aria-expanded',







            'true'







        );















    }























    function closeMobileSidebar() {















        body.classList.remove(







            'mobile-sidebar-open'







        );















        mobileSidebarLauncher?.setAttribute(







            'aria-expanded',







            'false'







        );















    }























    function syncSidebarForViewport() {















        closeMobileSidebar();















        if (desktopMedia.matches) {















            const collapsed =







                localStorage.getItem(







                    'architrackAdminSidebarCollapsed'







                ) === '1';















            setDesktopCollapsed(collapsed);















        } else {















            body.classList.remove(







                'sidebar-collapsed'







            );















        }















    }























    sidebarToggle?.addEventListener(







        'click',







        function () {















            if (desktopMedia.matches) {















                setDesktopCollapsed(







                    !body.classList.contains(







                        'sidebar-collapsed'







                    )







                );















            } else {















                closeMobileSidebar();















            }















        }







    );























    mobileSidebarLauncher?.addEventListener(







        'click',







        openMobileSidebar







    );























    topbarMenuButton?.addEventListener(







        'click',







        openMobileSidebar







    );























    sidebarBackdrop?.addEventListener(







        'click',







        closeMobileSidebar







    );























    document.addEventListener(







        'keydown',







        function (event) {















            if (







                event.key === 'Escape'







                &&







                body.classList.contains(







                    'mobile-sidebar-open'







                )







            ) {







                closeMobileSidebar();







            }















        }







    );























    sidebar?.querySelectorAll('a').forEach(







        function (link) {















            link.addEventListener(







                'click',







                function () {















                    if (!desktopMedia.matches) {







                        closeMobileSidebar();







                    }















                }







            );















        }







    );























    if (desktopMedia.addEventListener) {















        desktopMedia.addEventListener(







            'change',







            syncSidebarForViewport







        );















    } else {















        desktopMedia.addListener(







            syncSidebarForViewport







        );















    }























    syncSidebarForViewport();















});







